import { expect, test } from '@playwright/test'
import { addOffer, flow, inKeitaro, openNewCampaign, row, share, streamId } from './helpers'

test('create a campaign from the form and land in its editor', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Keitaro connected')).toBeVisible()
  await expect(page.getByRole('link', { name: /Demo campaign/ })).toBeVisible()
  await page.getByLabel('Name').fill('Spring promo')
  await page.getByLabel('GEO sent to google.com').fill('au')
  await page.keyboard.press('Enter')
  await page.getByLabel('Offer').fill('oxys')
  await page.getByRole('option', { name: /Oxys BE/ }).click()
  await page.getByRole('button', { name: 'Create in Keitaro' }).click()
  await expect(page).toHaveURL(/\/campaigns\/\d+$/)
  await expect(page.getByRole('heading', { name: 'Spring promo' })).toBeVisible()
  await expect(share(page, 3717)).toHaveText('100%')
  await expect(page.getByRole('region', { name: 'Flows without offers' })).toContainText('forced · country in AU → https://google.com')
})

test('add, rebalance, pin, remove, bring back, push', async ({ page }) => {
  await openNewCampaign(page, 3749)
  await addOffer(page, 'oxys', /Oxys BE/)
  await expect(share(page, 3749)).toHaveText('50%')
  await addOffer(page, 'joint', /Joint Rx RO/)
  await expect(share(page, 3749)).toHaveText('34%')
  await expect(share(page, 3717)).toHaveText('33%')
  await row(page, 3749).getByRole('button', { name: 'Pin share of offer 3749' }).click()
  await row(page, 11111).getByRole('button', { name: 'Remove' }).click()
  await expect(share(page, 3717)).toHaveText('66%')
  await expect(share(page, 3749)).toHaveText('34%')
  await row(page, 11111).getByRole('button', { name: 'Bring back' }).click()
  await expect(share(page, 11111)).toHaveText('33%')
  await expect(flow(page).getByText('3 pending changes')).toBeVisible()
  await flow(page).getByRole('button', { name: 'Push to KT' }).click()
  await expect(page.getByRole('button', { name: 'Fetch from KT' })).toBeVisible()
  await expect(flow(page).getByText(/pending change/)).toHaveCount(0)
  await expect(row(page, 3749).getByRole('button', { name: 'Unpin share of offer 3749' })).toBeVisible()
})

