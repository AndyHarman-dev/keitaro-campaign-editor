test('a share typed and pushed straight away reaches Keitaro', async ({ page }) => {
  await openNewCampaign(page, 3749)
  await addOffer(page, 'oxys', /Oxys BE/)
  await share(page, 3717).click()
  await page.getByLabel('Share for offer 3717').fill('80')
  await flow(page).getByRole('button', { name: 'Push to KT' }).click()
  await expect(page.getByRole('button', { name: 'Fetch from KT' })).toBeVisible()
  await expect(page.getByRole('alert')).toHaveCount(0)
  await page.getByRole('button', { name: 'Fetch from KT' }).click()
  await expect(share(page, 3717)).toHaveText('80%')
  await expect(share(page, 3749)).toHaveText('20%')
})

test('push is blocked when Keitaro changed, and Fetch & merge keeps the pending edit', async ({ page }) => {
  await openNewCampaign(page, 3749)
  await addOffer(page, 'oxys', /Oxys BE/)
  await flow(page).getByRole('button', { name: 'Push to KT' }).click()
  await expect(page.getByRole('button', { name: 'Fetch from KT' })).toBeVisible()
  await addOffer(page, 'joint', /Joint Rx RO/)
  await inKeitaro(page.request, `/streams/${await streamId(page)}/detach/3749`)
  await flow(page).getByRole('button', { name: 'Push to KT' }).click()
  const alert = flow(page).getByRole('alert')
  await expect(alert).toContainText('Flow 2 was changed in Keitaro since your last fetch.')
  await alert.getByRole('button', { name: 'Fetch & merge' }).click()
  await expect(row(page, 3749)).toContainText('removed in Keitaro')
  await expect(share(page, 11111)).toHaveText('50%')
  await flow(page).getByRole('button', { name: 'Push to KT' }).click()
  await expect(page.getByRole('button', { name: 'Fetch from KT' })).toBeVisible()
})

test('an offer archived in Keitaro is tagged and Remove drops it locally', async ({ page }) => {
  await openNewCampaign(page, 3749)
  await addOffer(page, 'cardio', /Cardio Fresh CZ/)
  await flow(page).getByRole('button', { name: 'Push to KT' }).click()
  await expect(page.getByRole('button', { name: 'Fetch from KT' })).toBeVisible()
  const sid = await streamId(page)
  await inKeitaro(page.request, `/streams/${sid}/detach/4242`)
  await inKeitaro(page.request, '/offers/4242/archive')
  await page.getByRole('button', { name: 'Fetch from KT' }).click()
  await expect(row(page, 4242)).toContainText('archived in Keitaro · can’t be restored')
  await expect(row(page, 4242).getByRole('button', { name: 'Bring back' })).toHaveCount(0)
  await row(page, 4242).getByRole('button', { name: 'Remove' }).click()
  await expect(row(page, 4242)).toHaveCount(0)
})

